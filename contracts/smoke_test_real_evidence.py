def make_session_factory():
    """An isolated SQLite session factory for the preparation flow."""
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker

    workdir = Path(tempfile.mkdtemp(prefix="terracycle_evidence_"))
    engine = create_engine(f"sqlite:///{(workdir / 'evidence.db').as_posix()}")
    session_factory = sessionmaker(bind=engine, autoflush=False)

    # SQLite has no regex operator, so the '~' check constraints must be dropped.
    saved = {t.name: t.constraints for t in Base.metadata.tables.values()}
    for table in Base.metadata.tables.values():
        table.constraints = [
            c for c in table.constraints
            if not hasattr(c, "sqltext") or "~" not in str(c.sqltext)
        ]
    try:
        Base.metadata.create_all(bind=engine)
    finally:
        for table in Base.metadata.tables.values():
            table.constraints = saved[table.name]

    return session_factory


def load_policy(policy_id: str) -> dict:
    """Load a verification policy from the shared fixture."""
    data = json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))
    policies = data.get("verification_policies", {})
    if policy_id not in policies:
        raise ValueError(f"Unknown verification policy '{policy_id}'")
    return policies[policy_id]


def prepare_real_commitment(session_factory):
    """Prepare a genuine plan and commitment with the authoritative backend code."""
    db = session_factory()
    try:
        db.add(
            Parcel(
                parcel_id=PARCEL_ID,
                name="Field 01 — Dolj, Romania",
                geometry_path="data/parcels/parcel_01.geojson",
                area_ha=42.50,
            )
        )
        db.commit()

        plan = create_plan(
            PlanRequest(
                parcel_id=PARCEL_ID,
                season_id=SEASON_ID,
                crop_history=CROP_HISTORY,
                treatments=[],
                requested_crop_id=REQUESTED_CROP_ID,
            ),
            db,
        )
        prepared = prepare_commitment(
            PrepareRequest(
                plan_id=plan.plan_id,
                rotation_id=plan.rotations[0].rotation_id,
                beneficiary_address=BENEFICIARY,
                verification_policy_id=POLICY_ID,
            ),
            db,
        )
        commitment = db.get(Commitment, prepared.commitment_id)
        if commitment is None:
            raise RuntimeError("The prepared commitment was not persisted.")
        return plan, commitment
    finally:
        db.close()


def generate_real_evidence(session_factory=None) -> dict:
    """
    Generate the genuine evidence of parcel_01.

    Reuses the existing verifier, the existing canonical evidence builder and
    the existing canonical hashing. Nothing is invented: the commitment comes
    from the authoritative preparation flow, the observations come from the
    real Sentinel-2 export and the verdict is whatever the verifier returns.
    """
    session_factory = session_factory or make_session_factory()
    plan, commitment = prepare_real_commitment(session_factory)

    policy = load_policy(commitment.verification_policy_id)
    verifier_result = verify_parcel(commitment.parcel_id, policy, str(EVIDENCE_DIR))
    evidence_doc, evidence_bytes, evidence_hash = build_evidence_document(
        verifier_result=verifier_result,
        commitment=commitment,
        policy=policy,
    )

    return {
        "plan_id": plan.plan_id,
        "commitment": commitment,
        "commitment_id": commitment.commitment_id,
        "plan_hash": commitment.plan_hash,
        "policy": policy,
        "verifier_result": verifier_result,
        "evidence_doc": evidence_doc,
        "evidence_bytes": evidence_bytes,
        "evidence_hash": evidence_hash,
        "verdict": verifier_result["verdict"],
        "verdict_code": verifier_result["verdict_code"],
    }


def safe_rpc_url(url: str) -> str:
    """A credential-free description of the RPC endpoint (never a token)."""
    parsed = urlsplit(url)
    host = parsed.hostname or ""
    if host not in ("127.0.0.1", "localhost", "::1"):
        return f"{parsed.scheme}://<non-local endpoint redacted>"
    port = f":{parsed.port}" if parsed.port else ""
    return f"{parsed.scheme}://{host}{port}"


def build_demo_document(
    evidence: dict,
    chain_id: int,
    rpc_url: str,
    registry,
    registry_address: str,
    deploy_tx_hash: str,
    receipt: dict,
    tx_hash: str,
) -> dict:
    """
    Build the presentation summary of a successful demonstration.

    Every value comes from the real execution: the verifier result, the canonical
    evidence bytes, the mined receipt and the contract storage. Nothing is
    invented and no secret is included.
    """
    from smoke_test import to_hex

    verifier_result = evidence["verifier_result"]
    quality = verifier_result["quality"]
    policy = evidence["policy"]
    commitment = evidence["commitment"]
    evidence_doc = evidence["evidence_doc"]

    log = receipt["logs"][0]
    event_recorder, event_recorded_at = decode_event_data(log)

    stored = registry.functions.getEvidence(evidence["commitment_id"]).call()
    stored_commitment_id, stored_evidence_hash, stored_verdict = stored[0], stored[1], stored[2]

    recomputed_hash = "0x" + hashlib.sha256(evidence["evidence_bytes"]).hexdigest()
    read_back_match = (
        to_hex(stored_commitment_id) == to_hex(evidence["commitment_id"])
        and to_hex(stored_evidence_hash) == to_hex(evidence["evidence_hash"])
        and stored_verdict == evidence["verdict_code"]
    )

    return {
        "schema_version": DEMO_SCHEMA_VERSION,
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "run": {
            "status": "success",
            "local_only": True,
            "network": "anvil-local",
            "chain_id": chain_id,
            "rpc_url": safe_rpc_url(rpc_url),
        },
        "parcel": {
            "parcel_id": commitment.parcel_id,
            "season_id": commitment.season_id,
            "satellite_provider": verifier_result["source"]["provider"],
            "satellite_dataset": verifier_result["source"]["dataset"],
            "satellite_method": verifier_result["source"]["method"],
            "source_csv": Path(verifier_result["source"]["csv_file"]).name,
            "observations_total": len(verifier_result["observations"]),
            "observations_valid": quality["valid_count"],
            "source_rows": quality["total_rows"],
        },
        "verification": {
            "policy_version": policy["policy_version"],
            "policy_type": policy["type"],
            "window_start": policy["window_start"],
            "window_end": policy["window_end"],
            "ndvi_threshold": policy["ndvi_threshold"],
            "required_fraction": policy["required_fraction"],
            "min_observations": policy["min_observations"],
            "verdict": evidence["verdict"],
            "verdict_code": evidence["verdict_code"],
            "reason_code": verifier_result["reason_code"],
            "reason": verifier_result["reason"],
            "evidence_quality": quality["evidence_quality"],
            "temporal_coverage": quality["temporal_coverage"],
            "evidence_quality_warnings": list(quality["warnings"]),
        },
        "evidence": {
            "schema_version": evidence_doc["schema_version"],
            "evidence_id": f"evidence-{commitment.parcel_id}-{commitment.season_id}",
            "commitment_id": evidence["commitment_id"],
            "plan_id": evidence["plan_id"],
            "plan_hash": evidence["plan_hash"],
            "evidence_hash": evidence["evidence_hash"],
            "evidence_hash_recomputed": recomputed_hash,
            "canonical_bytes_length": len(evidence["evidence_bytes"]),
        },
        "blockchain": {
            "network": "anvil-local",
            "chain_id": chain_id,
            "registry_address": registry_address,
            "deploy_tx_hash": deploy_tx_hash,
            "tx_hash": tx_hash,
            "receipt_status": receipt["status"],
            "event": {
                "name": "EvidenceRecorded",
                "commitment_id": to_hex(log["topics"][1]),
                "evidence_hash": to_hex(log["topics"][2]),
                "verdict_code": int(to_hex(log["topics"][3]), 16),
                "recorder": event_recorder,
                "recorded_at": event_recorded_at,
            },
            "on_chain": {
                "commitment_id": to_hex(stored_commitment_id),
                "evidence_hash": to_hex(stored_evidence_hash),
                "verdict_code": stored_verdict,
                "read_back_match": read_back_match,
            },
        },
        "integrity": {
            "evidence_hash_recomputed_matches": recomputed_hash == evidence["evidence_hash"],
            "transaction_receipt_successful": receipt["status"] == 1,
            "event_matches_evidence": (
                to_hex(log["topics"][1]) == to_hex(evidence["commitment_id"])
                and to_hex(log["topics"][2]) == to_hex(evidence["evidence_hash"])
                and int(to_hex(log["topics"][3]), 16) == evidence["verdict_code"]
            ),
            "on_chain_matches_generated": read_back_match,
            "verdict_preserved": (
                evidence["verdict_code"] == verifier_result["verdict_code"]
                == evidence_doc["verdict_code"]
            ),
        },
        "limitations": list(DEMO_LIMITATIONS),
    }


def decode_event_data(log: dict) -> tuple[str, int]:
    """Decode the non-indexed event fields (recorder, recordedAt)."""
    from eth_abi import decode as abi_decode

    recorder, recorded_at = abi_decode(["address", "uint256"], bytes(log["data"]))
    return Web3.to_checksum_address(recorder), int(recorded_at)


def write_demo_document(path: Path, document: dict) -> Path:
    """Write the summary atomically: a partial file is never left behind."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(document, indent=2, ensure_ascii=False, sort_keys=False) + "\n"

    handle = tempfile.NamedTemporaryFile(
        "w",
        encoding="utf-8",
        newline="\n",  # the repository stores text files with LF endings
        dir=str(path.parent),
        prefix=path.name + ".",
        suffix=".tmp",
        delete=False,
    )
    try:
        with handle as fh:
            fh.write(payload)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(handle.name, path)
    except Exception:
        try:
            os.unlink(handle.name)
        except OSError:
            pass
        raise
    return path


def remove_stale_output(path: Path) -> None:
    """A failed run must never leave a document that could be read as current."""
    path = Path(path)
    if not path.exists():
        return
    stat = path.stat()
    print(
        f"[WARN] removing the stale proof document {path} "
        f"(written {datetime.fromtimestamp(stat.st_mtime, timezone.utc).isoformat()}): "
        "a failed run must not leave a success document behind",
        file=sys.stderr,
    )
    path.unlink()


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description="Real satellite evidence on a local chain.")
    parser.add_argument(
        "--output",
        default=str(DEFAULT_OUTPUT_PATH),
        help="where to write the presentation summary (default: data/demo/latest_proof.json)",
    )
    parser.add_argument(
        "--no-export",
        action="store_true",
        help="run the demonstration without writing the presentation summary",
    )
    return parser.parse_args(argv)


def resolve_output_path(args) -> Path:
    path = Path(args.output)
    return path if path.is_absolute() else (Path.cwd() / path)


def main() -> int:
    args = parse_args()
    output_path = resolve_output_path(args)
    try:
        return run_demo(output_path, export=not args.no_export)
    except BaseException:
        # A failed run must never leave a success document behind.
        remove_stale_output(output_path)
        raise


def run_demo(output_path: Path, export: bool = True) -> int:
    rpc_url = os.environ.get("ANVIL_RPC_URL", "http://127.0.0.1:8545")
    private_key = os.environ.get("ANVIL_PRIVATE_KEY")
    if not private_key:
        fail(
            "ANVIL_PRIVATE_KEY is not set.\n"
            "        Start Anvil and copy one of the development keys it prints."
        )
    if not private_key.startswith("0x"):
        private_key = "0x" + private_key

    print("== TerraCycle :: REAL satellite evidence -> LOCAL blockchain ==")
    print(f"RPC URL        : {rpc_url}")

    print("\n-- generating genuine evidence for the parcel --")
    evidence = generate_real_evidence()
    verifier_result = evidence["verifier_result"]
    quality = verifier_result["quality"]

    print(f"Parcel         : {PARCEL_ID} ({evidence['commitment'].parcel_id})")
    print(f"Season         : {SEASON_ID}")
    print(f"Policy         : {evidence['policy']['policy_version']} "
          f"(window {evidence['policy']['window_start']} .. {evidence['policy']['window_end']})")
    print(f"Source CSV     : {verifier_result['source']['csv_file']}")
    print(f"Provider       : {verifier_result['source']['provider']} / {verifier_result['source']['dataset']}")
    print(f"Verdict        : {evidence['verdict']} (code {evidence['verdict_code']})")
    print(f"Reason         : {verifier_result['reason']}")
    print(f"Reason code    : {verifier_result['reason_code']}")
    print(f"Observations   : {len(verifier_result['observations'])} "
          f"({quality['valid_count']} valid of {quality['total_rows']} rows)")
    print(f"Evidence quality: {quality['evidence_quality']} "
          f"(temporal coverage {quality['temporal_coverage']})")
    for warning in quality["warnings"]:
        print(f"  warning      : {warning}")
    print(f"Plan id        : {evidence['plan_id']}")
    print(f"Commitment id  : {evidence['commitment_id']}")
    print(f"Plan hash      : {evidence['plan_hash']}")
    print(f"Evidence bytes : {len(evidence['evidence_bytes'])} canonical bytes")
    print(f"Evidence hash  : {evidence['evidence_hash']}")

    recomputed_hash = "0x" + hashlib.sha256(evidence["evidence_bytes"]).hexdigest()
    check(
        recomputed_hash == evidence["evidence_hash"],
        "SHA-256 recomputed from the canonical evidence bytes matches the generated hash",
    )
    check(
        evidence["evidence_doc"]["verdict_code"] == evidence["verdict_code"],
        "the canonical evidence document preserves the verifier verdict code",
    )
    check(
        evidence["commitment_id"] == evidence["commitment"].commitment_id,
        "the commitment id comes from the authoritative preparation flow",
    )

    print("\n-- deploying the registry on the local chain --")
    w3 = connect(rpc_url)
    check(
        w3.eth.chain_id == EXPECTED_CHAIN_ID,
        f"chain id is the documented local chain id {EXPECTED_CHAIN_ID} (got {w3.eth.chain_id})",
    )
    abi = load_abi()
    deployer = w3.eth.account.from_key(private_key).address
    verifier_address = os.environ.get("REGISTRY_VERIFIER", deployer)
    registry_address, deploy_hash = deploy_registry(
        w3, abi, load_bytecode(), verifier_address, deployer, private_key
    )
    print(f"Registry       : {registry_address}")
    print(f"Deploy tx      : {deploy_hash}")
    registry = w3.eth.contract(address=registry_address, abi=abi)

    print("\n-- recording the REAL evidence on chain --")
    receipt = record_evidence(
        w3,
        registry,
        evidence["commitment_id"],
        evidence["evidence_hash"],
        evidence["verdict_code"],
        verifier_address,
        private_key,
    )
    tx_hash = to_hex(receipt["transactionHash"])
    print(f"Tx hash        : {tx_hash}")

    print("\n-- verifying the receipt, the event and the stored record --")
    verify_recorded_evidence(
        registry,
        receipt,
        evidence["commitment_id"],
        evidence["evidence_hash"],
        evidence["verdict_code"],
        verifier_address,
    )

    stored_hash = to_hex(registry.functions.getEvidence(evidence["commitment_id"]).call()[1])
    check(
        stored_hash == recomputed_hash,
        "the on-chain evidence hash equals the hash recomputed from the canonical bytes",
    )

    print("\n-- summary --")
    print(f"Parcel         : {PARCEL_ID}")
    print(f"Verdict        : {evidence['verdict']} (code {evidence['verdict_code']})")
    print(f"Commitment id  : {evidence['commitment_id']}")
    print(f"Evidence hash  : {evidence['evidence_hash']}")
    print(f"Registry       : {registry_address}")
    print(f"Evidence tx    : {tx_hash} (status {receipt['status']})")
    print("note: local Anvil only — not a public testnet transaction, and not settlement")

    if not export:
        print("\nno presentation summary was written (--no-export)")
        return 0

    # Every integrity check passed: build and publish the summary.
    document = build_demo_document(
        evidence=evidence,
        chain_id=w3.eth.chain_id,
        rpc_url=rpc_url,
        registry=registry,
        registry_address=registry_address,
        deploy_tx_hash=deploy_hash,
        receipt=receipt,
        tx_hash=tx_hash,
    )
    for name, ok in document["integrity"].items():
        check(bool(ok), f"integrity check passed: {name}")

    written = write_demo_document(output_path, document)
    print(f"\nPresentation summary written to {written}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except AssertionError as exc:
        print(f"\nDEMONSTRATION FAILED: {exc}", file=sys.stderr)
        sys.exit(1)
    except Exception as exc:  # noqa: BLE001 - the script must fail loudly
        print(f"\nDEMONSTRATION ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        sys.exit(1)
