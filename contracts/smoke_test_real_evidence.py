#!/usr/bin/env python
"""
contracts/smoke_test_real_evidence.py — REAL satellite evidence on a LOCAL chain.

This demonstration replaces the synthetic test values of `smoke_test.py` with
genuine evidence generated by the existing project pipeline:

    backend/api/v1/plans.py        -> a real plan
    backend/api/v1/commitments.py  -> a real commitment (real commitment_id,
                                      real plan_hash)
    backend/ml/rules.py            -> the scientific verifier on the real
                                      Sentinel-2 CSV of parcel_01
    backend/services/evidence_builder.py -> the canonical evidence document
    backend/hashing.py             -> canonical bytes + SHA-256 evidence hash

The signed verification endpoint is NOT called: it would require the Node
signer, which is out of scope here. Everything up to (and including) the
canonical evidence hash is the existing, unmodified implementation.

This is an OFFLINE evidence-generation demonstration against a throwaway local
chain. It is NOT settlement authorization: the registry only stores metadata,
it does not verify satellite observations, organic compliance or payment
eligibility.

Usage:
    cd contracts
    forge build
    anvil --chain-id 31337                        # terminal 1
    export ANVIL_RPC_URL=http://127.0.0.1:8545
    export ANVIL_PRIVATE_KEY=<a development key printed by Anvil>
    python smoke_test_real_evidence.py            # terminal 2
"""

import hashlib
import json
import os
import sys
import tempfile
from pathlib import Path

CONTRACTS_DIR = Path(__file__).resolve().parent
REPO_ROOT = CONTRACTS_DIR.parent
for _path in (str(CONTRACTS_DIR), str(REPO_ROOT)):
    if _path not in sys.path:
        sys.path.insert(0, _path)

# backend.db builds its engine at import time; this demo uses its own isolated
# session, so the value only has to exist.
os.environ.setdefault("DATABASE_URL", "sqlite:///./test.db")

from web3 import Web3  # noqa: E402

from smoke_test import (  # noqa: E402  (local module, reused on purpose)
    EXPECTED_CHAIN_ID,
    check,
    connect,
    deploy_registry,
    fail,
    load_abi,
    load_bytecode,
    record_evidence,
    to_hex,
    verify_recorded_evidence,
)

from backend.api.v1.commitments import prepare_commitment  # noqa: E402
from backend.api.v1.plans import create_plan  # noqa: E402
from backend.ml.rules import verify_parcel  # noqa: E402
from backend.models import Base, Commitment, Parcel  # noqa: E402
from backend.schemas import HistoryItem, PlanRequest, PrepareRequest  # noqa: E402
from backend.services.evidence_builder import build_evidence_document  # noqa: E402

FIXTURE_PATH = REPO_ROOT / "data" / "fixtures" / "demo.json"
EVIDENCE_DIR = REPO_ROOT / "data" / "ndvi"

PARCEL_ID = "parcel_01"
SEASON_ID = "season-2024"
POLICY_ID = "cover-v1"
BENEFICIARY = "0x70997970C51812dc3A010C7d01b50e0d17dc79C8"
CROP_HISTORY = [
    HistoryItem(year=2022, crop_id="wheat"),
    HistoryItem(year=2023, crop_id="sunflower"),
]
REQUESTED_CROP_ID = "maize"


def make_session_factory():
    """An isolated SQLite session factory for the preparation flow."""
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker

    workdir = Path(tempfile.mkdtemp(prefix="terracycle_evidence_"))
    engine = create_engine(f"sqlite:///{(workdir / 'evidence.db').as_posix()}")
    session_factory = sessionmaker(bind=engine, autoflush=False)

    # SQLite has no regex operator, so the '~' check constraints must be dropped.
    saved = {t.name: t.constraints for t in Base.metadata.tables.values()}
    for table in Base.metadata.tables.values():
        table.constraints = [
            c for c in table.constraints
            if not hasattr(c, "sqltext") or "~" not in str(c.sqltext)
        ]
    try:
        Base.metadata.create_all(bind=engine)
    finally:
        for table in Base.metadata.tables.values():
            table.constraints = saved[table.name]

    return session_factory


def load_policy(policy_id: str) -> dict:
    """Load a verification policy from the shared fixture."""
    data = json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))
    policies = data.get("verification_policies", {})
    if policy_id not in policies:
        raise ValueError(f"Unknown verification policy '{policy_id}'")
    return policies[policy_id]


def prepare_real_commitment(session_factory):
    """Prepare a genuine plan and commitment with the authoritative backend code."""
    db = session_factory()
    try:
        db.add(
            Parcel(
                parcel_id=PARCEL_ID,
                name="Field 01 — Dolj, Romania",
                geometry_path="data/parcels/parcel_01.geojson",
                area_ha=42.50,
            )
        )
        db.commit()

        plan = create_plan(
            PlanRequest(
                parcel_id=PARCEL_ID,
                season_id=SEASON_ID,
                crop_history=CROP_HISTORY,
                treatments=[],
                requested_crop_id=REQUESTED_CROP_ID,
            ),
            db,
        )
        prepared = prepare_commitment(
            PrepareRequest(
                plan_id=plan.plan_id,
                rotation_id=plan.rotations[0].rotation_id,
                beneficiary_address=BENEFICIARY,
                verification_policy_id=POLICY_ID,
            ),
            db,
        )
        commitment = db.get(Commitment, prepared.commitment_id)
        if commitment is None:
            raise RuntimeError("The prepared commitment was not persisted.")
        return plan, commitment
    finally:
        db.close()


def generate_real_evidence(session_factory=None) -> dict:
    """
    Generate the genuine evidence of parcel_01.

    Reuses the existing verifier, the existing canonical evidence builder and
    the existing canonical hashing. Nothing is invented: the commitment comes
    from the authoritative preparation flow, the observations come from the
    real Sentinel-2 export and the verdict is whatever the verifier returns.
    """
    session_factory = session_factory or make_session_factory()
    plan, commitment = prepare_real_commitment(session_factory)

    policy = load_policy(commitment.verification_policy_id)
    verifier_result = verify_parcel(commitment.parcel_id, policy, str(EVIDENCE_DIR))
    evidence_doc, evidence_bytes, evidence_hash = build_evidence_document(
        verifier_result=verifier_result,
        commitment=commitment,
        policy=policy,
    )

    return {
        "plan_id": plan.plan_id,
        "commitment": commitment,
        "commitment_id": commitment.commitment_id,
        "plan_hash": commitment.plan_hash,
        "policy": policy,
        "verifier_result": verifier_result,
        "evidence_doc": evidence_doc,
        "evidence_bytes": evidence_bytes,
        "evidence_hash": evidence_hash,
        "verdict": verifier_result["verdict"],
        "verdict_code": verifier_result["verdict_code"],
    }


def main() -> int:
    rpc_url = os.environ.get("ANVIL_RPC_URL", "http://127.0.0.1:8545")
    private_key = os.environ.get("ANVIL_PRIVATE_KEY")
    if not private_key:
        fail(
            "ANVIL_PRIVATE_KEY is not set.\n"
            "        Start Anvil and copy one of the development keys it prints."
        )
    if not private_key.startswith("0x"):
        private_key = "0x" + private_key

    print("== TerraCycle :: REAL satellite evidence -> LOCAL blockchain ==")
    print(f"RPC URL        : {rpc_url}")

    print("\n-- generating genuine evidence for the parcel --")
    evidence = generate_real_evidence()
    verifier_result = evidence["verifier_result"]
    quality = verifier_result["quality"]

    print(f"Parcel         : {PARCEL_ID} ({evidence['commitment'].parcel_id})")
    print(f"Season         : {SEASON_ID}")
    print(f"Policy         : {evidence['policy']['policy_version']} "
          f"(window {evidence['policy']['window_start']} .. {evidence['policy']['window_end']})")
    print(f"Source CSV     : {verifier_result['source']['csv_file']}")
    print(f"Provider       : {verifier_result['source']['provider']} / {verifier_result['source']['dataset']}")
    print(f"Verdict        : {evidence['verdict']} (code {evidence['verdict_code']})")
    print(f"Reason         : {verifier_result['reason']}")
    print(f"Reason code    : {verifier_result['reason_code']}")
    print(f"Observations   : {len(verifier_result['observations'])} "
          f"({quality['valid_count']} valid of {quality['total_rows']} rows)")
    print(f"Evidence quality: {quality['evidence_quality']} "
          f"(temporal coverage {quality['temporal_coverage']})")
    for warning in quality["warnings"]:
        print(f"  warning      : {warning}")
    print(f"Plan id        : {evidence['plan_id']}")
    print(f"Commitment id  : {evidence['commitment_id']}")
    print(f"Plan hash      : {evidence['plan_hash']}")
    print(f"Evidence bytes : {len(evidence['evidence_bytes'])} canonical bytes")
    print(f"Evidence hash  : {evidence['evidence_hash']}")

    recomputed_hash = "0x" + hashlib.sha256(evidence["evidence_bytes"]).hexdigest()
    check(
        recomputed_hash == evidence["evidence_hash"],
        "SHA-256 recomputed from the canonical evidence bytes matches the generated hash",
    )
    check(
        evidence["evidence_doc"]["verdict_code"] == evidence["verdict_code"],
        "the canonical evidence document preserves the verifier verdict code",
    )
    check(
        evidence["commitment_id"] == evidence["commitment"].commitment_id,
        "the commitment id comes from the authoritative preparation flow",
    )

    print("\n-- deploying the registry on the local chain --")
    w3 = connect(rpc_url)
    check(
        w3.eth.chain_id == EXPECTED_CHAIN_ID,
        f"chain id is the documented local chain id {EXPECTED_CHAIN_ID} (got {w3.eth.chain_id})",
    )
    abi = load_abi()
    deployer = w3.eth.account.from_key(private_key).address
    verifier_address = os.environ.get("REGISTRY_VERIFIER", deployer)
    registry_address, deploy_hash = deploy_registry(
        w3, abi, load_bytecode(), verifier_address, deployer, private_key
    )
    print(f"Registry       : {registry_address}")
    print(f"Deploy tx      : {deploy_hash}")
    registry = w3.eth.contract(address=registry_address, abi=abi)

    print("\n-- recording the REAL evidence on chain --")
    receipt = record_evidence(
        w3,
        registry,
        evidence["commitment_id"],
        evidence["evidence_hash"],
        evidence["verdict_code"],
        verifier_address,
        private_key,
    )
    tx_hash = to_hex(receipt["transactionHash"])
    print(f"Tx hash        : {tx_hash}")

    print("\n-- verifying the receipt, the event and the stored record --")
    verify_recorded_evidence(
        registry,
        receipt,
        evidence["commitment_id"],
        evidence["evidence_hash"],
        evidence["verdict_code"],
        verifier_address,
    )

    stored_hash = to_hex(registry.functions.getEvidence(evidence["commitment_id"]).call()[1])
    check(
        stored_hash == recomputed_hash,
        "the on-chain evidence hash equals the hash recomputed from the canonical bytes",
    )

    print("\n-- summary --")
    print(f"Parcel         : {PARCEL_ID}")
    print(f"Verdict        : {evidence['verdict']} (code {evidence['verdict_code']})")
    print(f"Commitment id  : {evidence['commitment_id']}")
    print(f"Evidence hash  : {evidence['evidence_hash']}")
    print(f"Registry       : {registry_address}")
    print(f"Evidence tx    : {tx_hash} (status {receipt['status']})")
    print("note: local Anvil only — not a public testnet transaction, and not settlement")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except AssertionError as exc:
        print(f"\nDEMONSTRATION FAILED: {exc}", file=sys.stderr)
        sys.exit(1)
    except Exception as exc:  # noqa: BLE001 - the script must fail loudly
        print(f"\nDEMONSTRATION ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        sys.exit(1)
