"""
contracts/smoke_test_real_evidence.py — REAL satellite evidence on a LOCAL chain.

This demonstration replaces the synthetic test values of `smoke_test.py` with
genuine evidence generated by the existing project pipeline:

    backend/api/v1/plans.py        -> a real plan
    backend/api/v1/commitments.py  -> a real commitment (real commitment_id,
                                      real plan_hash)
    backend/ml/rules.py            -> the scientific verifier on the real
                                      Sentinel-2 CSV of parcel_01
    backend/services/evidence_builder.py -> the canonical evidence document
    backend/hashing.py             -> canonical bytes + SHA-256 evidence hash

The signed verification endpoint is NOT called: it would require the Node
signer, which is out of scope here. Everything up to (and including) the
canonical evidence hash is the existing, unmodified implementation.

This is an OFFLINE evidence-generation demonstration against a throwaway local
chain. It is NOT settlement authorization: the registry only stores metadata,
it does not verify satellite observations, organic compliance or payment
eligibility.

Usage:
    cd contracts
    forge build
    anvil --chain-id 31337                        # terminal 1
    export ANVIL_RPC_URL=http://127.0.0.1:8545
    export ANVIL_PRIVATE_KEY=<a development key printed by Anvil>
    python smoke_test_real_evidence.py            # terminal 2

The successful run can publish a presentation summary (a plain JSON document)
for a future read-only interface:

    python smoke_test_real_evidence.py --output data/demo/latest_proof.json

The summary is written ONLY after every integrity check passed, and it is
written atomically. It is a presentation summary: the canonical evidence bytes
and their SHA-256 hash remain the authoritative artefacts.
"""

